"""Write sources/synthetic.json from the cases registered in gen_synthetic.py."""

import json
from pathlib import Path

from gen_synthetic import CASES, NOT_REPRODUCIBLE

ROOT = Path(__file__).resolve().parent.parent
source = {
    "id": "synthetic",
    "title": "Synthetic HDF4 files, one storage feature each",
    "description": (
        "Files written by the HDF4 C library through tools/gen_synthetic.py. Each isolates "
        "one storage layout, compression coder, number type or metadata shape."
    ),
    "license": "CC0-1.0",
    "license_note": "CC0-1.0, public domain dedication",
    "links": [
        {
            "rel": "license",
            "href": "https://github.com/virtual-zarr/hdf4-examples/blob/main/LICENSE-GENERATED-DATA",
            "title": "CC0 1.0 Universal, for content generated by this project",
        }
    ],
    "datetime": "2026-11-16T00:00:00Z",
    "providers": [
        {"name": "virtual-zarr/hdf4-examples", "roles": ["producer"], "url": "https://github.com/virtual-zarr/hdf4-examples"}
    ],
    "items": [
        {
            "id": name,
            "description": description,
            **({"reproducible": False} if name in NOT_REPRODUCIBLE else {}),
            "via": [
                {
                    "href": "https://github.com/virtual-zarr/hdf4-examples/blob/main/tools/gen_synthetic.py",
                    "title": f"Generator case {name!r}",
                }
            ],
        }
        for name, (_, description) in CASES.items()
    ],
}
(ROOT / "sources" / "synthetic.json").write_text(json.dumps(source, indent=1) + "\n")
print(f"wrote sources/synthetic.json with {len(source['items'])} items")
